"""tac_plus-ng configuration adapter: structured snapshot → native configuration text.

Every identifier is validated (policy.NAME) and every string is quoted and escaped, so nothing from the UI can break
out of its token. Two renderings are produced from the same code path: the full file (with device keys and the LDAP
bind password, stored Fernet-encrypted and handed only to the deploy agent) and the redacted file (secrets as ***)
used for previews, diffs and version history.

Syntax follows the tac_plus-ng documentation of the pinned commit (docs/TACACS.md). The deploy agent runs
`tac_plus-ng -P` on every candidate before activation, so a construct the parser rejects is never activated.
"""
from __future__ import annotations

import difflib
import hashlib
from datetime import datetime, timezone

from .parse import FIELDS, FORMAT_KEY, LOG_FILES, format_string
from .policy import active, clients_in_scope, command_rules, deny_rules, ordered_mappings, validate_name
from .vendors import CAPABILITIES

LOG_DIR = "/tacacs/logs"
MAVIS_LDAP = "/usr/local/lib/mavis/mavis_tacplus-ng_ldap.pl"
PAMMAVIS = "/usr/local/sbin/pammavis"
REDACTED = "***"
TESTER = "sentinel_grid_tester"


def q(s) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def _re(p: str) -> str:
    return "/" + p.replace("/", "\\/") + "/"


def _or(conds: list[str]) -> str:
    return conds[0] if len(conds) == 1 else "(" + " || ".join(conds) + ")"


def profile_name(role: str, vendor: str) -> str:
    return f"r_{role}_{vendor}".replace("-", "_")


def _profile(snap: dict, role_id: int, vendor: str, now: datetime) -> list[str]:
    role = snap["roles"][role_id]
    prof = (role.get("vendor_profiles") or {}).get(vendor) or {}
    name = profile_name(role["name"], vendor)
    lines = [f"\tprofile {name} {{", f"\t\t# role {role['name']} on {CAPABILITIES[vendor]['label']}"]
    lines.append("\t\tenable 15 = login" if role.get("privileged") else "\t\tenable = deny")
    lines.append("\t\tscript {")
    if vendor == "fortinet":
        lines += ["\t\t\tif (service == fortigate) {"]
        if prof.get("admin_profile"):
            lines.append(f"\t\t\t\tadd admin_prof = {q(prof['admin_profile'])}")
        lines += ["\t\t\t\tpermit", "\t\t\t}", "\t\t\tdeny"]
    else:
        lines += ["\t\t\tif (service == shell) {", '\t\t\t\tif (cmd == "") {']
        if vendor == "ruckus" and "priv_lvl" in prof:
            lines.append(f"\t\t\t\t\tadd foundry-privlvl = {int(prof['priv_lvl'])}")
        elif "priv_lvl" in prof:
            lines.append(f"\t\t\t\t\tset priv-lvl = {int(prof['priv_lvl'])}")
        lines += ["\t\t\t\t\tpermit", "\t\t\t\t}"]
        for r in command_rules(snap, role_id, vendor, now):
            lines.append(f"\t\t\t\tif (cmd =~ {_re(r['regex'])}) {r['action']} # {r['source']}")
        lines.append(f"\t\t\t\t{role.get('default_command_action', 'deny')} # role default")
        lines += ["\t\t\t}", "\t\t\tdeny"]
    lines += ["\t\t}", "\t}"]
    return lines


def render(snap: dict, secrets: dict, *, redact: bool, now: datetime | None = None) -> str:
    """secrets: {"clients": {name: [key, (pending key)]}, "sources": {name: bind password}}"""
    now = now or datetime.now(timezone.utc)
    S = (lambda v: REDACTED) if redact else (lambda v: v)
    out = ["#!/usr/local/sbin/tac_plus-ng", f"# Generated by Sentinel Grid — do not edit by hand. {len(snap['clients'])} devices, "
           f"{len(snap['users'])} users, {len(snap['roles'])} roles.", "", "id = spawnd {", "\tbackground = no",
           "\tlisten { port = 49 }", "\tspawn {", "\t\tinstances min = 1", "\t\tinstances max = 32", "\t}", "}", "", "id = tac_plus-ng {"]
    for kind in FIELDS:
        out.append(f"\tlog tac{kind} {{")
        out.append(f"\t\tdestination = {LOG_DIR}/{LOG_FILES[kind]}")
        out.append("\t\ttimestamp = RFC5424")
        out.append(f"\t\t{FORMAT_KEY[kind]} format = {q(format_string(kind))}")
        out.append("\t}")
    out += ["\tauthentication log = tacauthc", "\tauthorization log = tacauthz", "\taccounting log = tacacct", "\tconnection log = tacconn", ""]
    directory = [s for s in snap["sources"] if s["enabled"] and s["kind"] in ("ldap", "ad", "pam")]
    for s in directory:
        validate_name(s["name"], "identity source name")
        out.append(f"\t# identity source {s['name']} ({s['kind']})")
        if s["kind"] == "pam":
            out += ["\tmavis module = external {", f"\t\texec = {PAMMAVIS} pammavis -s {validate_name(s['settings'].get('pam_service') or 'tac_plus', 'PAM service')}",
                    "\t}"]
            continue
        st = s.get("settings") or {}
        out.append("\tmavis module = external {")
        out.append(f"\t\tsetenv LDAP_SERVER_TYPE = {q('microsoft' if s['kind'] == 'ad' else 'generic')}")
        out.append(f"\t\tsetenv LDAP_HOSTS = {q(' '.join(st.get('hosts') or []))}")
        for k, envk in (("base", "LDAP_BASE"), ("group_base", "LDAP_BASE_GROUP"), ("filter", "LDAP_FILTER"), ("memberof_regex", "LDAP_MEMBEROF_REGEX"),
                        ("bind_dn", "LDAP_USER"), ("nested_group_depth", "LDAP_NESTED_GROUP_DEPTH")):
            if st.get(k) not in (None, ""):
                out.append(f"\t\tsetenv {envk} = {q(st[k])}")
        if st.get("bind_dn"):
            out.append(f"\t\tsetenv LDAP_PASSWD = {q(S(secrets.get('sources', {}).get(s['name'], '')))}")
        if st.get("starttls"):
            out.append('\t\tsetenv USE_STARTTLS = "1"')
        out.append("\t\tsetenv LDAP_CONNECT_TIMEOUT = \"3\"")
        out.append(f"\t\texec = {MAVIS_LDAP}")
        out.append("\t}")
    if directory:
        out += ["\tuser backend = mavis", "\tlogin backend = mavis", "\tpap backend = mavis", ""]
    windows = sorted({m["time_window"] for m in ordered_mappings(snap, now) if m.get("time_window")})
    wname = {w: f"tw{i + 1}" for i, w in enumerate(windows)}
    for w in windows:
        out.append(f"\ttime {wname[w]} {{ {q(w)} }}")
    for c in sorted(snap["clients"], key=lambda c: c["name"]):
        if not c.get("enabled", True):
            continue
        validate_name(c["name"], "device name")
        keys = secrets.get("clients", {}).get(c["name"]) or []
        if not keys:
            out.append(f"\t# {c['name']}: no shared secret, not rendered")
            continue
        out.append(f"\tdevice {c['name']} {{")
        out.append(f"\t\taddress = {c['address'] if '/' in c['address'] else c['address'] + ('/128' if ':' in c['address'] else '/32')}")
        for k in keys:
            out.append(f"\t\tkey = {q(S(k))}")
        out.append(f"\t\ttag = {c['vendor']}")
        out.append("\t}")
    tester = secrets.get("tester") or {}
    if tester.get("address") and tester.get("key"):
        out += [f"\tdevice {TESTER} {{", "\t\t# the SIEM's AAA testing center (authentication and accounting checks; no shell access)",
                f"\t\taddress = {tester['address'] if '/' in tester['address'] else tester['address'] + ('/128' if ':' in tester['address'] else '/32')}", f"\t\tkey = {q(S(tester['key']))}", "\t\ttag = tester", "\t}",
                "\tprofile r_tester {", "\t\tenable = deny", "\t\tscript { deny }", "\t}"]
    groups = sorted({m["principal"] for m in snap["mappings"] if m["principal_type"] == "group" and active(m, now)} |
                    {g for u in snap["users"] for g in (u.get("groups") or [])})
    for g in groups:
        out.append(f"\tgroup {validate_name(g, 'group name')}")
    used = sorted({(m["role_id"], c["vendor"]) for m in ordered_mappings(snap, now) for c in clients_in_scope(m, snap["clients"])})
    for role_id, vendor in used:
        out += _profile(snap, role_id, vendor, now)
    for u in sorted(snap["users"], key=lambda u: u["username"]):
        if u.get("source_kind") != "local" or not u.get("enabled", True) or not u.get("password_hash"):
            continue
        validate_name(u["username"], "user name")
        out.append(f"\tuser {u['username']} {{")
        out.append(f"\t\tpassword login = crypt {u['password_hash'] if not redact else REDACTED}")
        out.append("\t\tpassword pap = login")
        if u.get("groups"):
            out.append(f"\t\tmember = {','.join(u['groups'])}")
        vu = u.get("valid_until")
        if vu:
            out.append(f"\t\tvalid until = {str(vu)[:10]}")
        out.append("\t}")
    out += ["", "\truleset {"]
    for d in deny_rules(snap, now):
        conds = []
        if d["users"] is not None:
            conds.append(_or([f"user == {q(n)}" for n in d["users"]]))
        else:
            conds += [f"user != {q(n)}" for n in d.get("exclude", [])]
        if d["clients"] is not None:
            if not d["clients"]:
                continue
            conds.append(_or([f"device.name == {n}" for n in d["clients"]]))
        out += [f"\t\trule {d['id'].replace(':', '_')} {{", "\t\t\tscript {", f"\t\t\t\tif ({' && '.join(conds) or 'user =~ /./'}) deny", "\t\t\t}", "\t\t}"]
    if tester.get("address") and tester.get("key"):
        out += ["\t\trule tester {", "\t\t\tscript {", f"\t\t\t\tif (device.name == {TESTER}) {{", "\t\t\t\t\tprofile = r_tester", "\t\t\t\t\tpermit",
                "\t\t\t\t}", "\t\t\t}", "\t\t}"]
    for m in ordered_mappings(snap, now):
        role = snap["roles"][m["role_id"]]
        scope = clients_in_scope(m, snap["clients"])
        by_vendor: dict[str, list[str]] = {}
        for c in scope:
            by_vendor.setdefault(c["vendor"], []).append(c["name"])
        who = f"user == {q(m['principal'])}" if m["principal_type"] == "user" else f"member == {q(m['principal'])}"
        for vendor, names in sorted(by_vendor.items()):
            conds = [who]
            unscoped = not any(m.get(k) for k in ("scope_clients", "scope_sites", "scope_device_groups"))
            conds.append(f"device.tag == {vendor}" if unscoped else _or([f"device.name == {n}" for n in sorted(names)]))
            if m.get("time_window"):
                conds.append(f"time == {wname[m['time_window']]}")
            out += [f"\t\trule m{m['id']}_{vendor} {{", f"\t\t\t# {m['principal_type']} {m['principal']} → {role['name']} (priority {m.get('priority', 100)})",
                    "\t\t\tscript {", f"\t\t\t\tif ({' && '.join(conds)}) {{", f"\t\t\t\t\tprofile = {profile_name(role['name'], vendor)}", "\t\t\t\t\tpermit",
                    "\t\t\t\t}", "\t\t\t}", "\t\t}"]
    out += ["\t}", "}", ""]
    return "\n".join(out)


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def diff(old: str, new: str, a: str = "deployed", b: str = "candidate") -> str:
    return "".join(difflib.unified_diff(old.splitlines(keepends=True), new.splitlines(keepends=True), fromfile=a, tofile=b, n=3))
